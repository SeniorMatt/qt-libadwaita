"""Generate src/adwaitatokens_data.h from data/adwaita-1.10.json.

Reads schemes.<variant>.colors.<name> ({r,g,b,a}) for every name that is a token in src/adwaitatokens.h,
plus: radii (button->radius, card->radius_card, popover->radius_popover, check->radius_check, switch->radius_switch),
schemes.<variant>.opacities (border->border_opacity, disabled->disabled_opacity, focus_ring_alpha),
other_colors.tooltip_bg/tooltip_fg, and the per-accent standalone (text) colours -> kAdwaitaAccents[].
If the JSON is missing the placeholder header is left untouched.
"""
import json, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "data", "adwaita-1.10.json")
out = os.path.join(root, "src", "adwaitatokens_data.h")
if not os.path.exists(src):
    print("no data/adwaita-1.10.json: keeping placeholder tokens", file=sys.stderr)
    sys.exit(0)
d = json.load(open(src))
known = set(re.findall(r"X\((\w+)\)", open(os.path.join(root, "src", "adwaitatokens.h")).read()))

def css(c):
    return "rgba(%d,%d,%d,%g)" % (c["r"], c["g"], c["b"], c.get("a", 1.0))

rows = []
for vname, v in d["schemes"].items():
    for k, c in v["colors"].items():
        if k in known and isinstance(c, dict):
            rows.append((vname, k, css(c)))
    for k, key in (("border", "border_opacity"), ("disabled", "disabled_opacity"), ("focus_ring_alpha", "focus_ring_alpha")):
        if k in v.get("opacities", {}):
            rows.append((vname, key, str(v["opacities"][k])))
    for k in ("tooltip_bg", "tooltip_fg"):
        rows.append((vname, k, css(d["other_colors"][k])))
    for k, key in (("button", "radius"), ("card", "radius_card"), ("popover", "radius_popover"),
                   ("check", "radius_check"), ("switch", "radius_switch")):
        rows.append((vname, key, str(d["radii"][k])))
acc = d["accent"]["palette"]
std = d["accent"]["standalone_resolved_hex"]
with open(out, "w") as f:
    f.write("// SPDX-License-Identifier: GPL-2.0-or-later\n// GENERATED by tools/gen_tokens.py from data/adwaita-1.10.json. Do not edit.\n")
    f.write("static const AdwaitaTokenOverride kAdwaitaTokenOverrides[] = {\n")
    for r in rows: f.write('    {"%s", "%s", "%s"},\n' % r)
    f.write('    {"", "", ""}};\n')
    f.write("static const int kAdwaitaTokenOverrideCount = %d;\n" % len(rows))
    f.write("// name, accent-bg, standalone accent colour (light), (dark)\n")
    f.write("static const AdwaitaAccentEntry kAdwaitaAccents[] = {\n")
    for n, c in acc.items():
        f.write('    {"%s", 0x%02x%02x%02x, "%s", "%s"},\n' % (n, c["r"], c["g"], c["b"], std["light"][n], std["dark"][n]))
    f.write("};\n")
    f.write("static const int kAdwaitaAccentCount = %d;\n" % len(acc))
print(f"wrote {len(rows)} overrides, {len(acc)} accents to {out}")
