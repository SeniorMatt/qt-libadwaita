# ---------------------------------------------------------------- colours
def flat(c, over=(0, 0, 0)):
    a = c["a"]
    return tuple(round(c[k] * a + over[i] * (1 - a)) for i, k in enumerate("rgb"))


def hx(t):
    return "#%02x%02x%02x" % tuple(t)


def scheme(name):
    c = D["schemes"][name]["colors"]
    w = flat(c["window_bg"])
    return {
        "window_bg": w,
        "window_fg": flat(c["window_fg"], w),
        "hb_bg": flat(c["headerbar_bg"], w),
        "hb_backdrop": flat(c["headerbar_backdrop"], w),
        "hb_fg": flat(c["headerbar_fg"], flat(c["headerbar_bg"], w)),
        "hb_fg_raw": c["headerbar_fg"],
        # backdrop: libadwaita dims the header bar content to 0.5 opacity
        "hb_fg_backdrop": flat(dict(c["headerbar_fg"], a=c["headerbar_fg"]["a"] * 0.5), flat(c["headerbar_backdrop"], w)),
        "hb_fg_backdrop_full": flat(c["headerbar_fg"], flat(c["headerbar_backdrop"], w)),
        "popover_bg": flat(c["popover_bg"], w),
    }


