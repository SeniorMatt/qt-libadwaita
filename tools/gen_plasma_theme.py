def splash():
    for scheme_name, lid in (("light", "io.github.seniormatt.libadwaita"), ("dark", "io.github.seniormatt.libadwaita-dark")):
        s = SCHEMES[scheme_name]
        base = "look-and-feel/%s/contents/splash" % lid
        emit(base + "/Splash.qml", SPLASH_QML % (tokensource.active_name(), hx(s["window_bg"])))
        c = hx(s["window_fg"])
        # libadwaita-style spinner: a 270 degree arc with round caps (the QML rotates it)
        emit(base + "/images/spinner.svg",
             '<?xml version="1.0" encoding="UTF-8"?>\n<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64">\n'
             '<circle cx="32" cy="32" r="26" fill="none" stroke="%s" stroke-opacity="0.15" stroke-width="5"/>\n'
             '<path d="M32 6A26 26 0 1 1 6 32" fill="none" stroke="%s" stroke-width="5" stroke-linecap="round"/>\n</svg>\n' % (c, c))


def main():
    aurorae("Libadwaita", "Libadwaita", "light")
    aurorae("Libadwaita-Dark", "Libadwaita-Dark", "dark")
    desktoptheme()
    splash()
    check = "--check" in sys.argv
    bad = 0
    for rel, text in sorted(written.items()):
        p = os.path.join(OUT, rel)
        if check:
            if not os.path.exists(p) or open(p).read() != text:
                print("differs:", "plasma/" + rel)
                bad += 1
            continue
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as f:
            f.write(text)
    if check:
        sys.exit(1 if bad else 0)
    print("wrote %d files under plasma/" % len(written))


if __name__ == "__main__":
    main()
