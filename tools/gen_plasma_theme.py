def fmt(v):
    s = ("%.3f" % v).rstrip("0").rstrip(".")
    return s if s else "0"


# ---------------------------------------------------------------- shadows
def parse_shadow(s):
    """'0 0 14px 5px rgba(0,0,0,0.15), ...' -> [(dy, blur, spread, alpha)]"""
    out = []
    for m in re.finditer(r"(-?\d+)(?:px)?\s+(-?\d+)(?:px)?\s+(\d+)(?:px)?\s+(\d+)(?:px)?\s+rgba\(\s*0\s*,\s*0\s*,\s*\d+\s*,\s*([\d.]+)\)", s):
        out.append((int(m.group(2)), int(m.group(3)), int(m.group(4)), float(m.group(5))))
    assert out, "no shadow layers in " + s
    return out


def profile(layers, d, scale=1.0):
    """Shadow opacity at distance d (px) outside a straight window edge (gaussian blur of a spread box)."""
    keep = 1.0
    for _dy, blur, spread, a in layers:
        if blur == 0:
            v = a if d <= spread else 0.0
        else:
            sigma = blur / 2.0
            v = a * 0.5 * math.erfc((d - spread) / (sigma * math.sqrt(2)))
        keep *= 1 - v
    return (1 - keep) * scale


def stops(layers, extent, scale, reverse=False, mapper=None):
    """gradient stops for d = 0..extent (offset = mapper(d))."""
    end = profile(layers, extent, scale)
    out = []
    for d in range(extent + 1):
        a = max(0.0, profile(layers, d, scale) - end)
        off = mapper(d) if mapper else d / extent
        out.append((off, a))
    out.sort()
    return "".join('<stop offset="%s" stop-color="#000" stop-opacity="%s"/>' % (fmt(o), fmt(a)) for o, a in out)


class Defs:
    def __init__(self):
        self.items = []
        self.n = 0

    def add(self, xml):
        self.items.append(xml)

    def uid(self, p="g"):
        self.n += 1
        return "%s%d" % (p, self.n)


# ---------------------------------------------------------------- generic svg builders
def svg_doc(w, h, defs, body, style=""):
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">\n'
            '<!-- generated by tools/gen_plasma_theme.py from data/%s: do not edit -->\n'
            '<defs>%s%s</defs>\n%s</svg>\n' % (w, h, w, h, tokensource.active_name(), style, "".join(defs.items), body))


def group(id_, x, y, inner, tf=""):
    t = "translate(%s,%s)%s" % (fmt(x), fmt(y), (" " + tf) if tf else "")
    return '<g id="%s" transform="%s">%s</g>\n' % (id_, t, inner)


def lin(defs, x1, y1, x2, y2, st):
    i = defs.uid("lg")
    defs.add('<linearGradient id="%s" gradientUnits="userSpaceOnUse" x1="%s" y1="%s" x2="%s" y2="%s">%s</linearGradient>'
             % (i, fmt(x1), fmt(y1), fmt(x2), fmt(y2), st))
    return "url(#%s)" % i


def rad(defs, cx, cy, r, st):
    i = defs.uid("rg")
    defs.add('<radialGradient id="%s" gradientUnits="userSpaceOnUse" cx="%s" cy="%s" r="%s">%s</radialGradient>'
             % (i, fmt(cx), fmt(cy), fmt(r), st))
    return "url(#%s)" % i


def rect(x, y, w, h, fill, extra=""):
    return '<rect x="%s" y="%s" width="%s" height="%s" fill="%s"%s/>' % (fmt(x), fmt(y), fmt(w), fmt(h), fill, extra)


# ================================================================= 1. Aurorae
P = 24                    # shadow padding around the window
EDGE = P + WIN_R          # width of the left/right edge elements (shadow + the corner arc)
TOPH = P + TITLE_H        # height of the top elements (shadow + title bar)
BOT = P                   # bottom element: bottom border is 0, it is all shadow
SHADOW_LAYERS = parse_shadow(D["widgets"]["window_dialog"]["csd_shadow"])


def deco_elements(prefix, hdr, body, shadow_scale, defs):
    """The nine frame elements for one prefix ('decoration' or 'decoration-inactive'); returns (svg, height)."""
    w = 8
    H, B = hx(hdr), hx(body)
    parts = []

    def put(name, wd, ht, inner, tf=""):
        parts.append((name, wd, ht, inner, tf))

    # horizontal shadow ramps: left edge is d = P at x = 0 and d = 0 at x = P
    ramp_l = lambda: lin(defs, 0, 0, P, 0, stops(SHADOW_LAYERS, P, shadow_scale, mapper=lambda d: 1 - d / P))
    ramp_t = lambda: lin(defs, 0, 0, 0, P, stops(SHADOW_LAYERS, P, shadow_scale, mapper=lambda d: 1 - d / P))
    ramp_b = lambda: lin(defs, 0, 0, 0, P, stops(SHADOW_LAYERS, P, shadow_scale, mapper=lambda d: d / P))
    # top-left corner: radial from the arc centre
    def corner_tl():
        rg = rad(defs, EDGE, EDGE, EDGE, stops(SHADOW_LAYERS, P, shadow_scale, mapper=lambda d: (WIN_R + d) / EDGE))
        s = rect(0, 0, EDGE, EDGE, rg)
        s += rect(0, EDGE, EDGE, TOPH - EDGE, ramp_l())
        s += '<path d="M%d %d V%d A%d %d 0 0 1 %d %d V%d Z" fill="%s"/>' % (P, TOPH, EDGE, WIN_R, WIN_R, EDGE, P, TOPH, H)
        return s
    # bottom-left corner: the window's bottom corner is square (Qt apps cannot round their own corners)
    def corner_bl():
        rg = rad(defs, P, 0, P, stops(SHADOW_LAYERS, P, shadow_scale, mapper=lambda d: d / P))
        return rect(0, 0, P, BOT, rg) + rect(P, 0, EDGE - P, BOT, ramp_b()) + rect(P, 0, EDGE - P, 0.0001, B)

    put("topleft", EDGE, TOPH, corner_tl())
    put("top", w, TOPH, rect(0, 0, w, P, ramp_t()) + rect(0, P, w, TITLE_H, H))
    put("topright", EDGE, TOPH, '<g transform="translate(%d,0) scale(-1,1)">%s</g>' % (EDGE, corner_tl()))
    put("left", EDGE, w, rect(0, 0, P, w, ramp_l()) + rect(P, 0, EDGE - P, w, B))
    put("center", w, w, rect(0, 0, w, w, B))
    put("right", EDGE, w, '<g transform="translate(%d,0) scale(-1,1)">%s</g>' % (EDGE, rect(0, 0, P, w, ramp_l()) + rect(P, 0, EDGE - P, w, B)))
    put("bottomleft", EDGE, BOT, corner_bl())
    put("bottom", w, BOT, rect(0, 0, w, BOT, ramp_b()))
    put("bottomright", EDGE, BOT, '<g transform="translate(%d,0) scale(-1,1)">%s</g>' % (EDGE, corner_bl()))
    return parts


def layout_parts(prefix, parts, x0, y0, step_pad=10):
    """Place parts left to right on one row; returns (svg, width, height)."""
    out, x, hmax = "", x0, 0
    for name, wd, ht, inner, tf in parts:
        out += group(prefix + "-" + name, x, y0, inner)
        x += wd + step_pad
        hmax = max(hmax, ht)
    return out, x, hmax


def aurorae(variant, theme_name, scheme_name):
    s = SCHEMES[scheme_name]
    defs = Defs()
    body = ""
    y = 0
    width = 0
    rows = [("decoration", s["hb_bg"], s["window_bg"], 1.0),
            ("decoration-inactive", s["hb_backdrop"], s["window_bg"], 0.55)]
    for prefix, hdr, bodyc, sc in rows:
        parts = deco_elements(prefix, hdr, bodyc, sc, defs)
        svg, wd, ht = layout_parts(prefix, parts, 0, y)
        body += svg
        y += ht + 10
        width = max(width, wd)
    # maximized: only the centre element is used (the title bar, edge to edge)
    for prefix, hdr in (("decoration-maximized", s["hb_bg"]), ("decoration-maximized-inactive", s["hb_backdrop"])):
        body += group(prefix + "-center", 0, y, rect(0, 0, 8, TITLE_H, hx(hdr)))
        y += TITLE_H + 10
    emit("aurorae/%s/decoration.svg" % theme_name, svg_doc(width, y, defs, body))

    # ---- buttons: 24 px circles, glyphs stroked in the title colour
    fg = s["hb_fg"]
    fgi = s["hb_fg_backdrop_full"]   # inactive buttons: full colour, the state opacity below dims them
    hover_a, active_a, base_a = 0.15, 0.30, 0.10   # windowcontrols: currentColor 0.10 / hover 0.15 / active 0.30
    glyphs = {
        "close": '<path d="M8.5 8.5L15.5 15.5M15.5 8.5L8.5 15.5"/>',
        "minimize": '<path d="M8 15.5H16"/>',
        "maximize": '<rect x="8.4" y="8.4" width="7.2" height="7.2" rx="1.2"/>',
        "restore": '<rect x="8.4" y="10.4" width="5.2" height="5.2" rx="1"/><path d="M10.6 8.4V8.2a1 1 0 0 1 1-1H15.4a1 1 0 0 1 1 1V12.4a1 1 0 0 1-1 1H15.4"/>',
        "alldesktops": '<circle cx="12" cy="12" r="2.6" fill="currentColor" stroke="none"/>',
        "keepabove": '<path d="M8.5 14L12 10.5L15.5 14"/>',
        "keepbelow": '<path d="M8.5 10L12 13.5L15.5 10"/>',
        "help": '<path d="M9.9 9.8a2.2 2.2 0 1 1 3.4 1.8c-.8.5-1.2.9-1.2 1.7"/><path d="M12.1 15.9v.2"/>',
    }
    states = [("active", fg, base_a, 1.0), ("hover", fg, hover_a, 1.0), ("pressed", fg, active_a, 1.0),
              ("deactivated", fg, base_a, 0.35),
              ("inactive", fgi, base_a, 0.55), ("hover-inactive", fgi, hover_a, 0.7), ("pressed-inactive", fgi, active_a, 0.7),
              ("deactivated-inactive", fgi, base_a, 0.3)]
    for name, g in glyphs.items():
        bd, yy = "", 0
        for st, col, ca, op in states:
            c = hx(col)
            inner = ('<circle cx="12" cy="12" r="12" fill="%s" fill-opacity="%s"/>'
                     '<g color="%s" fill="none" stroke="%s" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round" opacity="%s">%s</g>'
                     % (c, fmt(ca * (1 if op >= 0.5 else op * 2)), c, c, fmt(op), g.replace("currentColor", c)))
            bd += group(st + "-center", 0, yy, inner)
            yy += 28
        emit("aurorae/%s/%s.svg" % (theme_name, name), svg_doc(24, yy, Defs(), bd))

    # ---- theme config
    def col(t):
        return "%d,%d,%d,255" % t
    layout = {
        "BorderLeft": 0, "BorderRight": 0, "BorderBottom": 0, "BorderTop": 0,
        "TitleEdgeTop": 11, "TitleEdgeBottom": TITLE_H - 24 - 11, "TitleEdgeLeft": 11, "TitleEdgeRight": 11,
        "TitleEdgeTopMaximized": 11, "TitleEdgeBottomMaximized": TITLE_H - 24 - 11,
        "TitleEdgeLeftMaximized": 11, "TitleEdgeRightMaximized": 11,
        # centre the title between the window edges when only the close button is on the right
        "TitleBorderLeft": 11 + BTN + 1, "TitleBorderRight": 12,
        "TitleHeight": 24, "ButtonWidth": BTN, "ButtonHeight": BTN, "ButtonSpacing": BTN_GAP, "ButtonMarginTop": 0,
        "ExplicitButtonSpacer": 10,
        "PaddingTop": P, "PaddingBottom": P, "PaddingLeft": P, "PaddingRight": P,
    }
    rc = ["[General]", "TitleAlignment=Center", "TitleVerticalAlignment=Center", "Animation=200",
          "ActiveTextColor=" + col(fg), "InactiveTextColor=" + col(s["hb_fg_backdrop"]),
          "UseTextShadow=false", "HaloActive=false", "HaloInactive=false",
          "LeftButtons=", "RightButtons=X", "Shadow=true", "DecorationPosition=0", "",
          "[Layout]"] + ["%s=%d" % kv for kv in layout.items()]
    emit("aurorae/%s/%src" % (theme_name, theme_name), "\n".join(rc) + "\n")
    emit("aurorae/%s/metadata.desktop" % theme_name,
         "[Desktop Entry]\nName=%s\nComment=GNOME libadwaita window decoration (%s)\n"
         "X-KDE-PluginInfo-Name=%s\nX-KDE-PluginInfo-Author=%s\nX-KDE-PluginInfo-Email=%s\n"
         "X-KDE-PluginInfo-Website=%s\nX-KDE-PluginInfo-Version=1.0\nX-KDE-PluginInfo-License=GPL\n"
         % (theme_name.replace("-", " "), scheme_name, theme_name, AUTHOR, EMAIL, WEBSITE))


